import { EventPlan } from '../types';

const STORAGE_KEY_CURRENT = 'eventgenie_current_plan';
const STORAGE_KEY_ALL = 'eventgenie_saved_plans';

export function loadCurrentPlan(): EventPlan | null {
  try {
    const raw = localStorage.getItem(STORAGE_KEY_CURRENT);
    if (!raw) return null;
    return JSON.parse(raw);
  } catch (err) {
    console.error('Failed to load current plan from localStorage:', err);
    return null;
  }
}

export function saveCurrentPlan(plan: EventPlan): void {
  try {
    localStorage.setItem(STORAGE_KEY_CURRENT, JSON.stringify(plan));
    savePlanToLibrary(plan);
  } catch (err) {
    console.error('Failed to save current plan to localStorage:', err);
  }
}

export function loadAllPlans(): EventPlan[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY_ALL);
    if (!raw) return [];
    return JSON.parse(raw);
  } catch (err) {
    console.error('Failed to load plans library:', err);
    return [];
  }
}

export function savePlanToLibrary(plan: EventPlan): void {
  try {
    const plans = loadAllPlans();
    const index = plans.findIndex((p) => p.id === plan.id);
    if (index >= 0) {
      plans[index] = plan;
    } else {
      plans.unshift(plan);
    }
    localStorage.setItem(STORAGE_KEY_ALL, JSON.stringify(plans));
  } catch (err) {
    console.error('Failed to save to plan library:', err);
  }
}

export function deletePlan(id: string): void {
  try {
    const plans = loadAllPlans().filter((p) => p.id !== id);
    localStorage.setItem(STORAGE_KEY_ALL, JSON.stringify(plans));
    const current = loadCurrentPlan();
    if (current?.id === id) {
      localStorage.removeItem(STORAGE_KEY_CURRENT);
    }
  } catch (err) {
    console.error('Failed to delete plan:', err);
  }
}

export function exportPlanAsMarkdown(plan: EventPlan): string {
  const { preferences, budget, timeline, vendors, creative, runOfShow, contingency } = plan;
  const sym = preferences.currency;

  let md = `# 🧞 EventGenie Master Blueprint: ${preferences.title}\n\n`;
  md += `**Event Type:** ${preferences.eventType.toUpperCase()} | **Date:** ${preferences.date} | **Guests:** ${preferences.guestCount} | **Budget:** ${sym} ${preferences.totalBudget.toLocaleString()}\n`;
  md += `**Location:** ${preferences.location} | **Theme:** ${creative.themeName}\n\n`;

  md += `## 🌟 Executive Concept & Summary\n${plan.aiSummary}\n\n`;

  md += `## 💰 Smart Programmatic Budget Breakdown\n`;
  md += `- **Total Budget:** ${sym} ${budget.totalBudget.toLocaleString()}\n`;
  md += `- **Allocated Sum:** ${sym} ${budget.allocatedTotal.toLocaleString()}\n`;
  md += `- **Contingency Buffer (${budget.contingencyPercentage}%):** ${sym} ${budget.contingencyAmount.toLocaleString()}\n`;
  md += `- **Cost Per Guest:** ${sym} ${budget.costPerGuest.toFixed(2)}\n\n`;

  md += `| Category | % | Allocated | Sub-Items |\n`;
  md += `|---|---|---|---|\n`;
  budget.categories.forEach((c) => {
    const items = c.subItems.map((s) => `${s.name} (${sym} ${s.estimatedCost.toLocaleString()})`).join(', ');
    md += `| ${c.name} | ${c.percentage}% | ${sym} ${c.allocatedAmount.toLocaleString()} | ${items} |\n`;
  });
  md += `\n`;

  if (budget.costSavingTips.length > 0) {
    md += `### 💡 Programmatic Cost-Saving Opportunities\n`;
    budget.costSavingTips.forEach((tip) => {
      md += `- **${tip.title}** (Est. Savings: ${sym} ${tip.potentialSavings.toLocaleString()}): ${tip.suggestion}\n`;
    });
    md += `\n`;
  }

  md += `## 🎨 Creative & Aesthetic Direction\n`;
  md += `- **Tagline:** "${creative.tagline}"\n`;
  md += `- **Mood:** ${creative.moodKeywords.join(', ')}\n`;
  md += `- **Color Palette:** ${creative.colorPalette.map((c) => `${c.name} (${c.hex})`).join(', ')}\n`;
  md += `\n**Decor Highlights:**\n`;
  creative.decorIdeas.forEach((d) => (md += `- ${d}\n`));
  md += `\n`;

  md += `## ⏱️ Day-of Run-of-Show\n`;
  md += `| Time | Activity | Lead | Location |\n`;
  md += `|---|---|---|---|\n`;
  runOfShow.forEach((r) => {
    md += `| ${r.time} | ${r.activity} | ${r.leadPerson} | ${r.location} |\n`;
  });
  md += `\n`;

  md += `## 🤝 Key Vendor Team\n`;
  md += `| Category | Vendor | Status | Est. Cost |\n`;
  md += `|---|---|---|---|\n`;
  vendors.forEach((v) => {
    md += `| ${v.category} | ${v.name} | ${v.status.toUpperCase()} | ${sym} ${v.estimatedCost.toLocaleString()} |\n`;
  });
  md += `\n`;

  md += `## 🛡️ Emergency Contingency Playbook\n`;
  md += `- **Weather Backup:** ${contingency.weatherFallback}\n`;
  md += `- **Technical / AV Failover:** ${contingency.technicalAVBackup}\n`;
  md += `- **Guest Surge Plan:** ${contingency.guestSurgePlan}\n`;
  md += `- **Vendor Cancellation:** ${contingency.vendorCancellationPlan}\n\n`;

  md += `---\n*Generated by EventGenie AI — GenAI-Powered Event & Financial Planning Assistant*`;
  return md;
}

